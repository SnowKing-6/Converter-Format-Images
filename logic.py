# السطر: استدعاء المكتبات اللازمة للمعالجة
# الوظيفة: تمكين البرنامج من فهم الصور وصيغة AVIF والتعامل مع الملفات
# لماذا: بدونها لن يعرف بايثون كيف يفتح "صورة" بل سيتعامل معها كملف نصي غير مفهوم
from PIL import Image
import pillow_avif  # لدعم AVIF
import os

def process_conversion(input_path, output_folder, target_format, quality=85):
    """
    هذا هو المحرك المسؤول عن عملية التحويل الفعلية.
    """
    try:
        # السطر: فتح الصورة الأصلية
        # الوظيفة: قراءة بكسلات الصورة ووضعها في الذاكرة (RAM)
        # لو حذفته: لن يجد البرنامج مادة خام ليعمل عليها
        with Image.open(input_path) as img:
            
            # السطر: استخراج اسم الملف الأساسي
            # الوظيفة: أخذ اسم الصورة بدون الامتداد (مثلاً image فقط)
            # لو حذفته: لن نعرف كيف نسمي الصورة الجديدة
            filename = os.path.splitext(os.path.basename(input_path))[0]
            
            # السطر: بناء مسار الحفظ الجديد
            # الوظيفة: دمج "مجلد الحفظ" + "اسم الصورة" + "الامتداد الجديد"
            # لماذا: لكي تظهر الصورة في المكان الذي اخترته بالاسم الصحيح
            output_path = os.path.join(output_folder, f"{filename}.{target_format.lower()}")

            # السطر: معالجة توافق الألوان (خاص بـ JPEG)
            # الوظيفة: تحويل الصور الشفافة لصور عادية إذا كان الهدف JPEG
            # لو حذفته: سينهار البرنامج عند تحويل صورة PNG شفافة إلى JPG
            if target_format.upper() in ["JPG", "JPEG"] and img.mode in ("RGBA", "P"):
                img = img.convert("RGB")
            
            # السطر: الحفظ النهائي والتحويل الفعلي
            # الوظيفة: ضغط البيانات وكتابتها على القرص الصلب بالصيغة الجديدة
            # لماذا: هذا هو السطر الذي يقوم بالعملية التي صنعت الأداة من أجلها
            img.save(output_path, quality=quality)
            
            # إرجاع نتيجة نجاح العملية مع المسار الجديد
            return True, output_path

    except Exception as e:
        # إرجاع نتيجة الفشل مع نص الخطأ
        return False, str(e)